<?php

declare(strict_types=1);

namespace AudiEdiPipe\Kernel;

/**
 * Immutable access to the configuration array using dot notation.
 */
final class Config
{
    /**
     * @param array<string, mixed> $values
     */
    public function __construct(private readonly array $values)
    {
    }

    public static function load(string $file): self
    {
        if (!is_file($file)) {
            return new self([]);
        }

        /** @var mixed $values */
        $values = require $file;

        return new self(is_array($values) ? $values : []);
    }

    public function get(string $key, mixed $default = null): mixed
    {
        $current = $this->values;
        foreach (explode('.', $key) as $segment) {
            if (!is_array($current) || !array_key_exists($segment, $current)) {
                return $default;
            }
            $current = $current[$segment];
        }

        return $current;
    }

    public function string(string $key, string $default = ''): string
    {
        $value = $this->get($key, $default);

        return is_scalar($value) ? (string) $value : $default;
    }

    public function int(string $key, int $default = 0): int
    {
        $value = $this->get($key, $default);

        return is_numeric($value) ? (int) $value : $default;
    }

    public function bool(string $key, bool $default = false): bool
    {
        $value = $this->get($key, $default);

        return is_bool($value) ? $value : (bool) $value;
    }

    public function isEmpty(): bool
    {
        return $this->values === [];
    }

    /**
     * @return array<string, mixed>
     */
    public function all(): array
    {
        return $this->values;
    }

    /**
     * @param array<string, mixed> $values
     */
    public static function export(array $values): string
    {
        return "<?php\n\n// Generated by the audiEdiPipe installer.\n\nreturn " . var_export($values, true) . ";\n";
    }
}
